export const TARGET_CURVES: EqTargetCurve[] = RAW_TARGETS.map(raw => ({
  name: raw.name,
  points: raw.points.map(([freq, gainDb]) => ({ freq, gainDb }))
}))

/** 目标曲线 → 十段参数带。 */
export function targetToFilters(name: string, bandCount = 10): EqFilter[] {
  const target = TARGET_CURVES.find(item => item.name === name)
  if (!target) return []
  return fitCurveToBands(target.points, bandCount)
}
